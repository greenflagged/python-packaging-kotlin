"""Regenerate the Unicode tables in PyUnicodeTables.kt from the running Python.

Two Python behaviours depend on Unicode character properties:

* ``re`` treats a character as a word character (``\\w``, and so for ``\\b``)
  when ``str.isalnum()`` is true or it is ``_``.
* ``repr()`` escapes characters for which ``str.isprintable()`` is false.

Java's equivalents depend on the JVM's Unicode version, and for ``\\b`` on the
JDK release, so these tables pin the Python behaviour instead.

Usage:
    python3 -I tools/gen_unicode_tables.py \\
        > src/main/kotlin/dev/greenflagged/pypackaging/internal/PyUnicodeTables.kt
"""

import sys
import unicodedata


def ranges(predicate):
    out = []
    for c in range(0x110000):
        if predicate(chr(c)):
            if out and out[-1][1] == c - 1:
                out[-1][1] = c
            else:
                out.append([c, c])
    return [x for r in out for x in r]


def emit(name, doc, flat):
    print(f"/** {doc} */")
    print(f"internal val {name}: IntArray = intArrayOf(")
    for i in range(0, len(flat), 12):
        print("    " + ", ".join(f"0x{x:X}" for x in flat[i : i + 12]) + ",")
    print(")")
    print()


print("// GENERATED by tools/gen_unicode_tables.py. Do not edit.")
print(f"// Source: Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.")
print("package dev.greenflagged.pypackaging.internal")
print()
emit(
    "PY_WORD_RANGES",
    "Inclusive [start, end] code point ranges that Python's `re` treats as `\\w`.",
    # Equivalent to re.fullmatch(r"\w", ch), verified for every code point; much faster.
    ranges(lambda ch: ch.isalnum() or ch == "_"),
)
emit(
    "PY_PRINTABLE_RANGES",
    "Inclusive [start, end] code point ranges for which Python's `str.isprintable()` is true.",
    ranges(lambda ch: ch.isprintable()),
)

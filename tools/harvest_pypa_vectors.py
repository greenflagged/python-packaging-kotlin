"""Extract pypa/packaging's parametrized test vectors into JSON fixtures.

The Kotlin conformance tests in src/test/kotlin/.../conformance re-implement each
upstream test function's assertions and run them over these vectors, so the vectors
themselves are never hand-copied.

Usage (from this repository's root):

    git clone https://github.com/pypa/packaging /tmp/packaging
    git -C /tmp/packaging checkout 26.3
    python3 -m venv /tmp/venv && /tmp/venv/bin/pip install pytest pretend packaging==26.3
    /tmp/venv/bin/python -I tools/harvest_pypa_vectors.py /tmp/packaging src/test/resources/pypa

Encoding of parameter values:
    str/int/bool/None/float -> JSON scalars (ints outside 2**53 as {"$int": "..."})
    tuple/list               -> JSON arrays
    set/frozenset            -> {"$set": [sorted items]}
    dict                     -> {"$dict": [[key, value], ...]}
    Version / Specifier / SpecifierSet / Marker / Requirement
                             -> {"$version": str} etc.
    anything else            -> {"$repr": repr(value)}
"""

from __future__ import annotations

import json
import os
import subprocess
import sys

FILES = ["test_version.py", "test_specifiers.py", "test_requirements.py", "test_markers.py", "test_utils.py"]


def encode(value):
    from packaging.markers import Marker
    from packaging.requirements import Requirement
    from packaging.specifiers import Specifier, SpecifierSet
    from packaging.version import Version

    if value is None or isinstance(value, (bool, str, float)):
        return value
    if isinstance(value, int):
        return value if abs(value) < 2**53 else {"$int": str(value)}
    if isinstance(value, (tuple, list)):
        return [encode(v) for v in value]
    if isinstance(value, (set, frozenset)):
        return {"$set": sorted((encode(v) for v in value), key=lambda x: json.dumps(x, sort_keys=True))}
    if isinstance(value, dict):
        return {"$dict": [[encode(k), encode(v)] for k, v in value.items()]}
    if isinstance(value, Version):
        return {"$version": str(value)}
    if isinstance(value, SpecifierSet):
        return {"$specifierset": str(value), "prereleases": value._prereleases}
    if isinstance(value, Specifier):
        return {"$specifier": str(value), "prereleases": value._prereleases}
    if isinstance(value, Marker):
        return {"$marker": str(value)}
    if isinstance(value, Requirement):
        return {"$requirement": str(value)}
    return {"$repr": repr(value)}


class Collector:
    def __init__(self):
        self.items = []

    def pytest_collection_modifyitems(self, session, config, items):
        self.items = list(items)


def main() -> None:
    upstream, out_dir = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    commit = subprocess.check_output(["git", "-C", upstream, "rev-parse", "HEAD"], text=True).strip()
    tag = subprocess.check_output(["git", "-C", upstream, "describe", "--tags"], text=True).strip()

    import pytest

    sys.path.insert(0, upstream)
    for name in FILES:
        collector = Collector()
        code = pytest.main(
            ["--collect-only", "-q", "-p", "no:cacheprovider", os.path.join(upstream, "tests", name)],
            plugins=[collector],
        )
        if code not in (0, 5):
            raise SystemExit(f"collection failed for {name}: {code}")
        tests: dict[str, dict] = {}
        for item in collector.items:
            func = item.originalname if hasattr(item, "originalname") else item.name
            cls = item.cls.__name__ if getattr(item, "cls", None) else None
            key = f"{cls}.{func}" if cls else func
            entry = tests.setdefault(key, {"cases": []})
            callspec = getattr(item, "callspec", None)
            if callspec is not None:
                entry["cases"].append({k: encode(v) for k, v in callspec.params.items()})
        doc = {
            "source": f"https://github.com/pypa/packaging/blob/{commit}/tests/{name}",
            "upstream_version": tag,
            "upstream_commit": commit,
            "license": "Apache-2.0 OR BSD-2-Clause; Copyright (c) Donald Stufft and individual contributors",
            "note": "Generated by tools/harvest_pypa_vectors.py. Do not edit by hand.",
            "tests": tests,
        }
        path = os.path.join(out_dir, name.replace(".py", ".json"))
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(doc, fh, indent=1, ensure_ascii=False, sort_keys=False)
            fh.write("\n")
        total = sum(len(t["cases"]) for t in tests.values())
        print(f"{name}: {len(tests)} test functions, {total} parametrized cases -> {path}")


if __name__ == "__main__":
    main()

import java.io.File

/**
 * Replays cases generated by `tools/differential/generate.py` (which ran Python
 * `packaging` on them) and fails on any difference. Run with:
 *
 *     python3 -I tools/differential/generate.py --seed 1 --count 2000 --out build/differential/cases.json
 *     ./gradlew differentialTest -Pdifferential.cases=build/differential/cases.json
 */
@Tag("differential")
class DifferentialTest {

    private val mismatches = ArrayList<String>()
    private val counts = LinkedHashMap<String, Int>()

    @Test
    fun matchesPythonPackaging() {
        val path = System.getProperty("differential.cases").orEmpty()
        if (path.isBlank()) fail<Unit>("Set -Pdifferential.cases=<file> (see tools/differential/generate.py)")
        val doc = Json.parseToJsonElement(File(path).readText()).jsonObject
        val environments = doc["environments"]!!.jsonArray.map { it.jsonObject }
        val overrides = doc["extra_overrides"]!!.jsonArray.map { it.jsonObject }
        val cases = doc["cases"]!!.jsonObject

        cases.forEach { (kind, list) ->
            for (case in list.jsonArray.map { it.jsonObject }) {
                counts.merge(kind, 1, Int::plus)
                try {
                    check(kind, case, environments, overrides)
                } catch (e: Throwable) {
                    mismatch(kind, case, "Kotlin threw ${e::class.simpleName}: ${e.message}")
                }
            }
        }
        println(
            "Differential: ${counts.values.sum()} cases (packaging ${doc["packaging_version"]?.jsonPrimitive?.content}, " +
                "seed ${doc["seed"]}) $counts, ${mismatches.size} mismatches",
        )
        if (mismatches.isNotEmpty()) {
            fail<Unit>("${mismatches.size} mismatches with Python packaging. First ones:\n" + mismatches.take(40).joinToString("\n\n"))
        }
    }

    private fun mismatch(kind: String, case: JsonObject, detail: String) {
        val input = case["input"] ?: case["versions"]
        mismatches.add("[$kind] input=$input\n  $detail")
    }

    private fun expect(kind: String, case: JsonObject, what: String, expected: JsonElement?, actual: JsonElement) {
        if (expected != actual) mismatch(kind, case, "$what:\n    python: $expected\n    kotlin: $actual")
    }

    private fun check(kind: String, case: JsonObject, environments: List<JsonObject>, overrides: List<JsonObject>) {
        val input = case["input"]?.jsonPrimitive?.content
        if (case.containsKey("python_internal_error")) {
            // Python accepted the input but then failed internally. This library must reject it outright.
            val rejected = runCatching {
                when (kind) {
                    "version" -> Version.parse(input!!)
                    "specifier" -> Specifier.parse(input!!)
                    "specifier_set" -> SpecifierSet.parse(input!!)
                    "marker" -> Marker.parse(input!!)
                    "requirement" -> Requirement.parse(input!!)
                    "wheel" -> Filenames.parseWheel(input!!)
                    "sdist" -> Filenames.parseSdist(input!!)
                    else -> error("unexpected kind $kind")
                }
            }.exceptionOrNull() is PackagingException
            if (!rejected) mismatch(kind, case, "Python failed internally (${case["python_internal_error"]}); Kotlin accepted it")
            return
        }
        when (kind) {
            "version" -> {
                expect(kind, case, "parse", case["parse"], call { describe(Version.parse(input!!)) })
                expect(kind, case, "canonical", case["canonical"], call { str(Version.canonicalize(input!!)) })
                expect(kind, case, "canonical_keep_zero", case["canonical_keep_zero"], call { str(Version.canonicalize(input!!, false)) })
            }
            "version_order" -> {
                val versions = case["versions"]!!.jsonArray.map { Version.parse(it.jsonPrimitive.content) }
                val matrix = versions.map { a ->
                    versions.joinToString("") { b -> a.compareTo(b).let { if (it < 0) "<" else if (it > 0) ">" else "=" } }
                }
                expect(kind, case, "matrix", case["matrix"], JsonArray(matrix.map(::JsonPrimitive)))
                for (i in versions.indices) for (j in versions.indices) {
                    if (versions[i] == versions[j] && versions[i].hashCode() != versions[j].hashCode()) {
                        mismatch(kind, case, "equal versions ${versions[i]} and ${versions[j]} have different hash codes")
                    }
                }
            }
            "specifier" -> checkSpecifier(kind, case, input!!)
            "specifier_set" -> checkSpecifierSet(kind, case, input!!)
            "marker" -> checkMarker(kind, case, input!!, environments, overrides)
            "requirement" -> {
                val actual = try {
                    val r = Requirement.parse(input!!)
                    buildJsonObject {
                        put("ok", buildJsonObject {
                            put("str", r.toString())
                            put("name", r.name)
                            put("url", r.url)
                            put("extras", JsonArray(r.extras.sorted().map(::JsonPrimitive)))
                            put("specifier", r.specifier.toString())
                            put("marker", r.marker?.toString())
                        })
                    }
                } catch (e: PackagingException) {
                    buildJsonObject {
                        put("error", errorName(e))
                        put("message", e.message)
                    }
                }
                expect(kind, case, "parse", case["parse"], actual)
            }
            "name" -> {
                expect(kind, case, "canonical", case["canonical"], call { str(Names.canonicalize(input!!)) })
                expect(kind, case, "validated", case["validated"], call { str(Names.canonicalize(input!!, validate = true)) })
                expect(kind, case, "is_normalized", case["is_normalized"], JsonPrimitive(Names.isNormalized(input!!)))
            }
            "wheel" -> if (!isNonAsciiInterpreterRejection(case)) expect(kind, case, "parse", case["parse"], call {
                val w = Filenames.parseWheel(input!!)
                buildJsonObject {
                    put("name", w.name)
                    put("version", w.version.toString())
                    put("build", w.buildTag?.let { JsonArray(listOf(JsonPrimitive(it.number.toString()), JsonPrimitive(it.suffix))) } ?: JsonNull)
                    put("tags", JsonArray(w.tags.map { it.toString() }.sorted().map(::JsonPrimitive)))
                }
            })
            "sdist" -> expect(kind, case, "parse", case["parse"], call {
                val s = Filenames.parseSdist(input!!)
                buildJsonObject {
                    put("name", s.name)
                    put("version", s.version.toString())
                }
            })
            else -> error("unknown case kind $kind")
        }
    }

    private fun checkSpecifier(kind: String, case: JsonObject, input: String) {
        val override = case["override"]!!.jsonPrimitive.booleanOrNull
        val candidates = case["candidates"]!!.jsonArray.map { it.jsonPrimitive.content }
        val spec = try {
            Specifier.parse(input, override)
        } catch (e: PackagingException) {
            expect(kind, case, "parse", case["parse"], buildJsonObject { put("error", errorName(e)) })
            return
        }
        expect(kind, case, "parse", case["parse"], buildJsonObject {
            put("ok", buildJsonObject {
                put("str", spec.toString())
                put("operator", spec.operator)
                put("version", spec.version)
                put("prereleases", spec.prereleases)
            })
        })
        val contains = case["contains"]?.jsonObject ?: return
        for ((p, label) in PRERELEASE_OPTIONS) {
            expect(kind, case, "contains(prereleases=$label)", contains[label],
                JsonArray(candidates.map { JsonPrimitive(spec.contains(it, p)) }))
            expect(kind, case, "filter(prereleases=$label)", case["filter"]!!.jsonObject[label],
                JsonArray(spec.filter(candidates, p).map(::JsonPrimitive)))
        }
    }

    private fun checkSpecifierSet(kind: String, case: JsonObject, input: String) {
        val override = case["override"]!!.jsonPrimitive.booleanOrNull
        val candidates = case["candidates"]!!.jsonArray.map { it.jsonPrimitive.content }
        val set = try {
            SpecifierSet.parse(input, override)
        } catch (e: PackagingException) {
            expect(kind, case, "parse", case["parse"], buildJsonObject { put("error", errorName(e)) })
            return
        }
        expect(kind, case, "parse", case["parse"], buildJsonObject {
            put("ok", buildJsonObject {
                put("str", set.toString())
                put("prereleases", set.prereleases)
                put("size", set.size)
            })
        })
        val contains = case["contains"]?.jsonObject ?: return
        for ((p, label) in PRERELEASE_OPTIONS) {
            for ((installed, instLabel) in listOf(null to "None", true to "True")) {
                expect(kind, case, "contains(prereleases=$label, installed=$instLabel)", contains["$label/$instLabel"],
                    JsonArray(candidates.map { JsonPrimitive(set.contains(it, p, installed)) }))
            }
            expect(kind, case, "filter(prereleases=$label)", case["filter"]!!.jsonObject[label],
                JsonArray(set.filter(candidates, p).map(::JsonPrimitive)))
        }
        expect(kind, case, "is_unsatisfiable", case["unsatisfiable"], JsonPrimitive(set.isUnsatisfiable()))
    }

    private fun checkMarker(kind: String, case: JsonObject, input: String, environments: List<JsonObject>, overrides: List<JsonObject>) {
        val marker = try {
            Marker.parse(input)
        } catch (e: PackagingException) {
            expect(kind, case, "parse", case["parse"], buildJsonObject {
                put("error", errorName(e))
                put("message", e.message)
            })
            return
        }
        expect(kind, case, "parse", case["parse"], buildJsonObject { put("ok", marker.toString()) })
        val results = ArrayList<JsonElement>()
        for (env in environments) {
            for (extra in overrides) {
                val builder = MarkerEnvironment.builder()
                (env + extra).forEach { (k, v) ->
                    if (v is JsonArray) builder.setValues(k, v.map { it.jsonPrimitive.content }.toSet()) else builder.set(k, v.jsonPrimitive.content)
                }
                val built = builder.build()
                for (context in listOf(EvaluateContext.METADATA, EvaluateContext.LOCK_FILE, EvaluateContext.REQUIREMENT)) {
                    results.add(
                        try {
                            JsonPrimitive(marker.evaluate(built, context))
                        } catch (e: PackagingException) {
                            JsonPrimitive(errorName(e))
                        },
                    )
                }
            }
        }
        val expected = case["evaluate"]!!.jsonArray
        if (expected != JsonArray(results)) {
            val diffs = expected.indices.filter { expected[it] != results[it] }.take(5).joinToString { i ->
                val env = i / (overrides.size * 3)
                val extra = (i / 3) % overrides.size
                val ctx = listOf("metadata", "lock_file", "requirement")[i % 3]
                "env#$env extra=${overrides[extra]} context=$ctx: python=${expected[i]} kotlin=${results[i]}"
            }
            mismatch(kind, case, "evaluate (marker '$marker'): $diffs")
        }
    }

    // Known difference: wheels with a non-ASCII interpreter tag are rejected (Python accepts
    // any str.isidentifier()). Skip only when Python accepted such a wheel and Kotlin rejected it.
    private fun isNonAsciiInterpreterRejection(case: JsonObject): Boolean {
        val ok = case["parse"]?.jsonObject?.get("ok") as? JsonObject ?: return false
        val interpreters = ok["tags"]!!.jsonArray.map { it.jsonPrimitive.content.substringBefore('-') }
        if (interpreters.all { i -> i.all { it.code < 0x80 } }) return false
        return runCatching { Filenames.parseWheel(case["input"]!!.jsonPrimitive.content) }
            .exceptionOrNull() is dev.greenflagged.pypackaging.InvalidWheelFilenameException
    }

    private fun describe(v: Version): JsonElement = buildJsonObject {
        put("str", v.toString())
        put("public", v.public)
        put("base_version", v.baseVersion)
        put("epoch", v.epoch.toString())
        put("release", JsonArray(v.release.map { JsonPrimitive(it.toString()) }))
        put("pre", v.pre?.let { JsonArray(listOf(JsonPrimitive(it.kind.label), JsonPrimitive(it.number.toString()))) } ?: JsonNull)
        put("post", v.post?.toString())
        put("dev", v.dev?.toString())
        put("local", v.local)
        put("is_prerelease", v.isPrerelease)
        put("is_postrelease", v.isPostrelease)
        put("is_devrelease", v.isDevrelease)
        put("major", v.major.toString())
        put("minor", v.minor.toString())
        put("micro", v.micro.toString())
    }

    private fun str(s: String): JsonElement = JsonPrimitive(s)

    private fun call(body: () -> JsonElement): JsonElement = try {
        buildJsonObject { put("ok", body()) }
    } catch (e: PackagingException) {
        buildJsonObject { put("error", errorName(e)) }
    }

    // InvalidVersionException -> "InvalidVersion", matching Python's exception class names.
    private fun errorName(e: PackagingException): String = e::class.simpleName!!.removeSuffix("Exception")

    private companion object {
        val PRERELEASE_OPTIONS = listOf(null to "None", true to "True", false to "False")
    }
}
